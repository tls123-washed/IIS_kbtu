export function language() {
  try { return localStorage.getItem('campus-language') === 'en' ? 'en' : 'ru'; }
  catch { return 'ru'; }
}

export const locale = () => language() === 'en' ? 'en-GB' : 'ru-KZ';

export function t(text) {
  if (language() !== 'en' || typeof text !== 'string') return text;
  if (text.startsWith('Проверьте поля формы (')) return text.replace('Проверьте поля формы', 'Check the form fields');
  return Object.hasOwn(en, text) ? en[text] : text;
}
